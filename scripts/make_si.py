"""Generate the Supporting-Information LaTeX tables (paper/si_tables.tex) from the result CSVs,
so numbers are exact (no hand-transcription). Each table is a booktabs tabular wrapped in a
table environment with an S-numbered caption/label. Run: /opt/anaconda3/bin/python3 scripts/make_si.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

FINAL = Path("results/final")
ROOT = Path("results")
OUT = Path("paper/si_tables.tex")


def tbl(df, caption, label, colfmt=None, floatfmt="%.3f"):
    body = df.to_latex(index=False, escape=True, column_format=colfmt,
                       float_format=lambda x: (floatfmt % x), na_rep="--")
    body = body.replace(r"\toprule", r"\toprule").replace("tabular", "tabular")  # keep booktabs
    # adjustbox max-width shrinks a too-wide table to the text width (shrink-only; narrow tables
    # are left untouched), so no Supporting Table runs off the page.
    return (f"\\begin{{table}}[htbp]\n\\centering\n\\caption{{{caption}}}\n"
            f"\\label{{{label}}}\n\\small\n"
            f"\\begin{{adjustbox}}{{max width=\\linewidth}}\n{body}\\end{{adjustbox}}\n"
            f"\\end{{table}}\n\n")


def tbl_long(df, caption, label, colfmt=None, floatfmt="%.3f"):
    """Page-breaking long table (longtable) for tall tables that overflow a single float."""
    return df.to_latex(index=False, escape=True, longtable=True, column_format=colfmt,
                       float_format=lambda x: (floatfmt % x), na_rep="--",
                       caption=caption, label=label) + "\n\n"


def main():
    parts = ["% Auto-generated by scripts/make_si.py -- do not hand-edit; rerun the script.\n\n"]

    # S0: model x analysis availability matrix (which model/dataset enters which analysis, and why
    # not, so every "six datasets / eight models" statement is read against its actual coverage).
    avail = pd.DataFrame([
        {"Analysis": "Conformal width + coverage", "Models": "RF, MolFormer, ChemFM, Uni-Mol, TabPFN",
         "Datasets": "6", "Coverage / reason for gaps": "TabPFN only on the 4 small datasets (out of regime on QM7/QM8)"},
        {"Analysis": "Per-fold significance (CD)", "Models": "Ridge, SVR, GBM, RF, TabPFN, MolFormer, ChemFM, Chemprop",
         "Datasets": "BACE-1", "Coverage / reason for gaps": "Uni-Mol omitted from the per-fold omnibus"},
        {"Analysis": "Cross-dataset CD", "Models": "RF, MolFormer, ChemFM, Uni-Mol",
         "Datasets": "6", "Coverage / reason for gaps": "complete blocks only; TabPFN excluded (not on QM)"},
        {"Analysis": "MC-Dropout (native)", "Models": "MolFormer; mean-variance MLP proxy",
         "Datasets": "MolFormer: 4 drug-like; MLP: 6", "Coverage / reason for gaps": "ChemFM, Chemprop, Uni-Mol native MC-Dropout not run"},
        {"Analysis": "Deep / tree ensembles (native)", "Models": "MolFormer, ChemFM, Chemprop; RF",
         "Datasets": "deep: BACE-1; RF: 6", "Coverage / reason for gaps": "deep ensembles = cross-seed variance on BACE"},
        {"Analysis": "AD-conditional coverage", "Models": "8 models (BACE); RF, MolFormer, ChemFM, Uni-Mol (multi)",
         "Datasets": "BACE-1; 4 drug-like", "Coverage / reason for gaps": "QM7, QM8 omitted (random split: AD near-degenerate)"},
        {"Analysis": "CQR", "Models": "GBM, MolFormer, Chemprop, Uni-Mol",
         "Datasets": "4 drug-like", "Coverage / reason for gaps": "QM7/QM8 omitted (as for AD)"},
        {"Analysis": "Dual split (exchangeability)", "Models": "RF (fixed diagnostic)",
         "Datasets": "6", "Coverage / reason for gaps": "RF used as a single diagnostic model"},
    ])
    parts.append(tbl(avail, "Model-by-analysis availability matrix: which models and datasets enter "
                        "each analysis, and the reason for any gaps. Not every model is evaluated in "
                        "every analysis; statements of ``six datasets / eight models'' should be read "
                        "against this matrix.", "si:availability", colfmt="p{2.5cm}p{3.6cm}p{2.0cm}p{3.4cm}"))

    # S1: full per-dataset conformal width + coverage + MAE
    if (FINAL / "conformal_full.csv").exists():
        d = pd.read_csv(FINAL / "conformal_full.csv")
        d = d[["dataset", "model", "empirical_coverage", "mean_width", "test_mae"]].rename(
            columns={"empirical_coverage": "coverage", "mean_width": "width", "test_mae": "MAE"})
        parts.append(tbl(d, "Split-conformal empirical coverage, mean interval width, and test MAE "
                            "per dataset and model (nominal coverage 0.90).", "si:conformal"))

    # S1b: coverage uncertainty -- k/n and Wilson 95% CI (so a sub-0.90 point estimate is read
    # against sampling error; conformal's guarantee is marginal finite-sample under exchangeability).
    if (FINAL / "coverage_ci.csv").exists():
        c = pd.read_csv(FINAL / "coverage_ci.csv")
        c["95% CI"] = c.apply(lambda r: f"[{r.ci95_lo:.3f}, {r.ci95_hi:.3f}]", axis=1)
        c = c[["dataset", "model", "n_test", "covered", "coverage", "95% CI", "cal_n", "q_index"]]
        parts.append(tbl(c, "Coverage uncertainty: covered/$n_\\text{test}$, empirical coverage, and a "
                            "Wilson 95\\% CI per dataset and model (nominal 0.90). $\\text{cal\\_n}$ is the "
                            "calibration-set size and $q_\\text{index}=\\lceil(\\text{cal\\_n}+1)(1-\\alpha)\\rceil$ "
                            "the conformal order-statistic rank. A point estimate below 0.90 whose CI includes "
                            "0.90 is not significantly invalid; only ESOL/Lipophilicity Uni-Mol and QM8 "
                            "RF/ChemFM have a CI entirely below 0.90.", "si:coverageci", floatfmt="%.3f"))

    # S2: multi-seed conformal error bars
    if (FINAL / "conformal_multiseed.csv").exists():
        d = pd.read_csv(FINAL / "conformal_multiseed.csv")
        for c in ["width_mean", "width_std", "cov_mean", "cov_std"]:
            d[c] = d[c].round(3)
        parts.append(tbl(d, "Multi-seed conformal interval width and coverage "
                            "(mean and s.d. over seeds).", "si:multiseed"))

    # S3a: UQ-extra (MLP Gaussian-NLL / MC-Dropout / TempScale / conformal)
    if (FINAL / "uq_extra.csv").exists():
        parts.append(tbl(pd.read_csv(FINAL / "uq_extra.csv"),
                         "Non-conformal UQ on a mean-variance MLP: 90\\% Gaussian-interval coverage "
                         "and width for Gaussian-NLL, MC-Dropout, temperature scaling, and split "
                         "conformal on the same model.", "si:uqextra"))

    # S3b: deep MC-Dropout + deep/tree ensembles vs conformal
    if (FINAL / "mc_dropout_deep.csv").exists():
        parts.append(tbl(pd.read_csv(FINAL / "mc_dropout_deep.csv"),
                         "MC-Dropout (30 passes) on the MolFormer foundation model vs split conformal "
                         "on the same model, by dataset.", "si:mcdeep"))
    if (FINAL / "uq_baselines.csv").exists():
        d = pd.read_csv(FINAL / "uq_baselines.csv")
        for c in ["conformal_coverage", "conformal_width"]:
            if c in d.columns:
                d[c] = pd.to_numeric(d[c], errors="coerce").round(3)
        parts.append(tbl(d, "Ensemble-variance Gaussian intervals (RF tree ensemble; deep ensembles "
                            "of the foundation models) vs split conformal.", "si:ensemble"))

    # S4: random vs scaffold dual split (exchangeability)
    if (FINAL / "gap4_dual_split.csv").exists():
        d = pd.read_csv(FINAL / "gap4_dual_split.csv")
        keep = [c for c in ["dataset", "n", "n_scaffolds", "cov_random", "cov_scaffold", "coverage_drop"] if c in d.columns]
        parts.append(tbl(d[keep], "Conformal coverage under matched random vs Murcko-scaffold splits "
                            "(exchangeability). Positive drop = scaffold under-covers relative to random.",
                         "si:dualsplit"))

    # S5: fingerprint config + feature-selection ablation
    if (FINAL / "fp_config_selection.csv").exists():
        d = pd.read_csv(FINAL / "fp_config_selection.csv")
        for c in ["MAE", "MAE_std", "PearsonR"]:
            if c in d.columns:
                d[c] = d[c].round(3)
        parts.append(tbl(d, "Fingerprint configuration and feature-selection ablation (random forest): "
                            "Morgan radius/nBits sweep and variance/mutual-information/Lasso selection.",
                         "si:fpsel"))

    # S6: per-fold 8-model significance + omnibus ranks
    if (FINAL / "perfold_8model_significance.csv").exists():
        parts.append(tbl(pd.read_csv(FINAL / "perfold_8model_significance.csv"),
                         "Per-fold (BACE-1, $N=50$ scaffold-grouped CV folds) Nadeau--Bengio corrected "
                         "$t$-test vs the TabPFN control, Holm-corrected. Confirmatory for the "
                         "pre-specified classic-model comparison (Ridge/SVR/GBM/RF); the three deep models "
                         "(MolFormer/ChemFM/Chemprop) were designated as held out, so their rows "
                         "are exploratory.", "si:perfold"))
    if (FINAL / "perfold_8model_omnibus.csv").exists():
        o = pd.read_csv(FINAL / "perfold_8model_omnibus.csv")
        ar = o[[c for c in o.columns if c.startswith("avgrank_")]].T.reset_index()
        ar.columns = ["model", "avg_rank"]
        ar["model"] = ar["model"].str.replace("avgrank_", "", regex=False)
        ar = ar.sort_values("avg_rank")
        parts.append(tbl(ar, "Per-fold average ranks across the eight models (lower = better; "
                            f"Friedman p = {o.friedman_p.iloc[0]:.1e}).", "si:ranks"))

    # S7: Optuna hyperparameters
    sj = Path("results/tuning/summary.json")
    if sj.exists():
        rows = []
        for r in json.loads(sj.read_text()):
            rows.append({"model": r["model"], "rep": r["rep"],
                         "best_params": ", ".join(f"{k}={v}" for k, v in r["best_params"].items())})
        parts.append(tbl(pd.DataFrame(rows), "Optuna-selected hyperparameters for the classic models "
                            "(5-fold CV on the training split).", "si:hparams",
                         colfmt="llp{0.62\\linewidth}"))  # wrap the long best_params column

    # S8a: BACE-1 8-model AD-conditional coverage -- the table behind the main-text AD figure.
    p = FINAL / "conformal_ad_coverage.csv"
    if p.exists():
        adb = pd.read_csv(p)
        # LaTeX-safe headers: raw "<"/">" render as wrong glyphs in text mode.
        adb.columns = ["model", "low (Tan 0.0--0.4)", "med (Tan 0.4--0.6)", "high (Tan 0.6--1.0)"]
        parts.append(tbl(adb, "Applicability-domain--conditional conformal coverage on BACE-1 for all "
                         "eight models, by Tanimoto-to-nearest-train stratum (nominal 0.90). This is the "
                         "table behind the main-text AD figure: most models collapse out of domain while "
                         "TabPFN and MolFormer hold near 0.90. The low-similarity stratum is small "
                         "($n\\approx10$), so it is exploratory.", "si:adcov"))
    # S8b: multi-dataset AD-stratified conditional coverage (four datasets x four backbones x three
    # strata = 48 rows -> too tall for a single float, so render as a page-breaking longtable).
    p = FINAL / "conformal_ad.csv"
    if p.exists():
        parts.append(tbl_long(pd.read_csv(p), "Applicability-domain--stratified conditional conformal "
                         "coverage across the four bioactivity/physicochemical datasets (four models: "
                         "RF, MolFormer, ChemFM, Uni-Mol), "
                         "by Tanimoto-to-nearest-train similarity stratum. QM7/QM8 are omitted: under "
                         "the random splits of these small molecules the Tanimoto applicability domain is "
                         "near-degenerate (test $\\approx$ train).", "si:adcovmulti"))
    # S: CQR (same four datasets; QM7/QM8 omitted as above)
    p = FINAL / "cqr_summary.csv"
    if p.exists():
        parts.append(tbl(pd.read_csv(p), "Conformalized quantile regression (CQR): interval width "
                         "and coverage per model on the four bioactivity/physicochemical datasets "
                         "(QM7/QM8 omitted, as for the AD analysis).", "si:cqr"))
    # S: leakage audit (the four predefined-split regression datasets; QM7/QM8 use random splits)
    p = FINAL / "split_leakage.csv"
    if p.exists():
        parts.append(tbl(pd.read_csv(p), "Split leakage audit for the four predefined-split regression "
                         "datasets: canonical-SMILES duplicates, InChIKey-14 collisions, scaffold overlap, "
                         "and Tanimoto$>$0.85 fraction. QM7/QM8 use random splits (no predefined-split "
                         "leakage to audit).", "si:leak"))

    OUT.write_text("".join(parts))
    print(f"wrote {OUT} ({len(parts) - 1} tables)")


if __name__ == "__main__":
    main()
